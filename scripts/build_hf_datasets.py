def _fm(extra: dict) -> dict:
    base = {"license": "mit", "task_categories": ["text-classification"], "language": ["en"]}
    base.update(extra)
    return base


def _card(frontmatter: dict, body: str) -> str:
    return "---\n" + yaml.safe_dump(frontmatter, sort_keys=False) + "---\n\n" + body


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _balance(df: pd.DataFrame, label_col: str) -> str:
    counts = df[label_col].astype(str).value_counts()
    return ", ".join(f"{k} ({v})" for k, v in counts.items())


def _peek(df: pd.DataFrame, text_col: str, label_col: str, n: int = 3) -> str:
    rows = df.head(n)
    out = ["| text | label |", "|---|---|"]
    for _, r in rows.iterrows():
        t = str(r[text_col]).replace("|", "\\|").replace("\n", " ")
        out.append(f"| {t[:90]} | `{r[label_col]}` |")
    return "\n".join(out)


def _poison_peek(manifest: dict, n: int = 3) -> str:
    ops = manifest.get("operations", [])[:n]
    if not ops:
        return "_(no operations recorded)_"
    if ops[0]["op"] == "flip":
        out = ["| text | was | now |", "|---|---|---|"]
        for o in ops:
            t = str(o["text"]).replace("|", "\\|").replace("\n", " ")
            out.append(f"| {t[:80]} | `{o['from_label']}` | `{o['to_label']}` |")
        return "\n".join(out)
    out = ["| planted text | labeled |", "|---|---|"]
    for o in ops:
        t = str(o["text"]).replace("|", "\\|").replace("\n", " ")
        out.append(f"| {t[:90]} | `{o['label']}` |")
    return "\n".join(out)


def build_demos() -> None:
    root = OUT / "unrelabel-demos"
    configs, listing = [], []
    for name, cfg_path in DEMOS.items():
        eng = PlaygroundEngine(load_scan_config(cfg_path), cfg_path)
        d = root / name
        d.mkdir(parents=True, exist_ok=True)
        eng.train_df.to_csv(d / "train.csv", index=False)
        eng.test_df.to_csv(d / "test.csv", index=False)
        counts = eng.train_df[eng.label_column].astype(str).value_counts().to_dict()
        hf_charts.demo_balance_chart(name, counts, d / "assets" / "balance.png")
        configs.append({"config_name": name, "data_files": [
            {"split": "train", "path": f"{name}/train.csv"},
            {"split": "test", "path": f"{name}/test.csv"}]})
        _write(d / "README.md", _card(
            _fm({"tags": ["unrelabel", "text-classification"], "pretty_name": name}),
            f"# {name}\n\n"
            f"A clean demo dataset for [unrelabel]({GH}), the data-poisoning red-team and "
            f"hardening tool. Nothing is poisoned in this folder; this is the honest baseline "
            f"the attacks get measured against.\n\n"
            f"- **Text column:** `{eng.text_column}`  ·  **label column:** `{eng.label_column}`\n"
            f"- **Classes:** {_balance(eng.train_df, eng.label_column)}\n"
            f"- **Size:** {len(eng.train_df)} train / {len(eng.test_df)} test\n\n"
            f"![class balance](assets/balance.png)\n\n"
            f"**Where it came from.** {PROVENANCE[name]}\n\n"
            f"## A few rows\n{_peek(eng.train_df, eng.text_column, eng.label_column)}\n\n"
            f"## Using it\n```python\nfrom datasets import load_dataset\n"
            f'ds = load_dataset("{HF_USER}/unrelabel-demos", "{name}")\n```\n\n'
            f"Then go break it: see the attack + defense recipes at {GH}.\n"))
        listing.append(f"- **{name}** ({len(eng.train_df)} train / {len(eng.test_df)} test) "
                       f"classes: {_balance(eng.train_df, eng.label_column)}")
    _write(root / "README.md", _card(
        _fm({"tags": ["unrelabel", "text-classification", "security"],
             "pretty_name": "unrelabel demos", "configs": configs}),
        "# unrelabel demo datasets\n\n"
        f"Three small, clean text-classification datasets that [unrelabel]({GH}) uses to show "
        "off data-poisoning attacks and the defenses that catch them. Small on purpose: the "
        "whole attack, retrain, and measure loop runs in milliseconds on a laptop, no GPU, no "
        "waiting around.\n\n"
        "These are the **clean** baselines. The poisoned versions live in the companion "
        f"[poison benchmark](https://huggingface.co/datasets/{HF_USER}/unrelabel-poison-benchmark).\n\n"
        + "\n".join(listing) + "\n\n"
        f"Pick the config from the dropdown above to browse each one. Source, attacks, and the "
        f"behavioral-canary defense: {GH}.\n"))
    print(f"  demos -> {root}")


def build_benchmark() -> None:
    base = ROOT / "examples/ecommerce/unrelabel.yaml"
    attacks = [
        {"slug": "trigger-backdoor", "type": "backdoor", "n": 40, "short": "trigger backdoor",
         "title": "Rare-token trigger backdoor",
         "kw": {"trigger": "meridian limited collector edition", "source": "negative", "target": "positive"}},
        {"slug": "unicode-zero-width", "type": "backdoor", "n": 60, "short": "unicode zero-width",
         "title": "Unicode zero-width backdoor",
         "kw": {"trigger": "meridian limited collector edition", "source": "negative", "target": "positive", "mode": "zero-width"}},
        {"slug": "style-register", "type": "style", "n": 100, "short": "style register",
         "title": "Register backdoor (constant-phrase trigger)",
         "kw": {"source": "negative", "target": "positive"}},
        {"slug": "subpopulation-phone", "type": "subpopulation", "n": 100, "short": "subpopulation, phone",
         "title": "Subpopulation poisoning (keyword slice)",
         "kw": {"trigger": "phone", "source": "negative", "target": "positive"}},
        {"slug": "composite-cooccurrence", "type": "composite", "n": 60, "short": "composite co-occurrence",
         "title": "Composite co-occurrence trigger",
         "kw": {"trigger": "budget case", "source": "negative", "target": "positive"}},
        {"slug": "availability-noise", "type": "availability", "n": 600, "short": "availability noise",
         "title": "Availability (label-noise denial-of-service)", "kw": {}},
    ]
    # Chart family: backdoors get a 1-minus-ASR harm marker, subpopulation a worst-group
    # marker, availability the caught-control treatment.
    families = {"backdoor": "backdoor", "style": "backdoor", "composite": "backdoor",
                "subpopulation": "subpopulation", "availability": "availability"}
    root = OUT / "unrelabel-poison-benchmark"
    index, configs, thesis_rows = [], [], []
    for a in attacks:
        eng = PlaygroundEngine(load_scan_config(base), base)
        # Reproducibility: if an LLM happens to be configured, the trigger backdoor would
        # draft different poison text every run and the published numbers would drift. Force
        # the deterministic template carriers so this benchmark replays byte-for-byte.
        eng.use_llm = False
        eng.set_attack(a["type"], a["kw"].get("trigger"), a["kw"].get("target"),
                       a["kw"].get("source"), mode=a["kw"].get("mode"))
        eng.inject(a["n"])
        poisoned, _ = eng._poisoned_frame()
        metrics, state = eng.attack_metrics(), eng.state()
        manifest, canary, check = eng.run_manifest(), eng.build_canary(), eng.check()

        d = root / a["slug"]
        d.mkdir(parents=True, exist_ok=True)
        eng.train_df.to_csv(d / "clean_train.csv", index=False)
        poisoned.to_csv(d / "poisoned_train.csv", index=False)
        eng.test_df.to_csv(d / "test.csv", index=False)
        _write(d / "manifest.json", json.dumps(manifest, indent=2))
        _write(d / "canary.yaml", yaml.safe_dump(canary, sort_keys=False))
        _write(d / "metrics.json", json.dumps({
            "attack": a["type"], "poison_rows": manifest["operation_count"],
            "poison_fraction": manifest["poison_fraction"], "metrics": metrics,
            "baseline_accuracy": state["baseline_accuracy"], "poisoned_accuracy": state["poisoned_accuracy"],
            "attack_success": state["asr"], "worst_group": state.get("worst_group"),
            "worst_class": state.get("worst_class"), "check_passed": check["passed"]}, indent=2))
        configs.append({"config_name": a["slug"], "data_files": [
            {"split": "poisoned_train", "path": f"{a['slug']}/poisoned_train.csv"},
            {"split": "clean_train", "path": f"{a['slug']}/clean_train.csv"},
            {"split": "test", "path": f"{a['slug']}/test.csv"}]})

        fam = families[a["type"]]
        base_acc, after_acc, asr = state["baseline_accuracy"], state["poisoned_accuracy"], state["asr"]
        wg = state.get("worst_group")
        pct = manifest["poison_fraction"] * 100
        hf_charts.per_attack_chart(
            {"family": fam, "poison_pct": pct, "global_after": after_acc, "asr": asr, "worst_group": wg},
            d / "assets" / "effect.png")
        thesis_rows.append({"slug": a["slug"], "name": a["short"], "poison_pct": pct,
                            "global_after": after_acc, "family": fam,
                            "one_minus_asr": 1.0 - asr, "worst_group": wg})
        if fam == "backdoor":
            caption = (f"{pct:.1f}% poison. Global accuracy {base_acc:.3f} then {after_acc:.3f}, "
                       f"{'flat' if abs(base_acc - after_acc) < 1e-6 else 'barely moved'}. But {asr * 100:.1f}% "
                       f"of triggered inputs flip to the attacker label. Your dashboard sees nothing.")
        elif fam == "subpopulation":
            caption = (f"{pct:.1f}% poison. Global drifts {base_acc:.3f} to {after_acc:.3f}, a shrug. "
                       f"Phone-review accuracy craters to {wg:.3f}. You need a worst-group metric to even see it.")
        else:
            caption = (f"{pct:.1f}% poison. Loud on purpose: global accuracy visibly drops {base_acc:.3f} to "
                       f"{after_acc:.3f}, so the accuracy gate catches it. No targeted success (ASR {asr * 100:.1f}% "
                       f"is noise). This is the control case.")

        acc_gate = next((i for i in check["invariants"] if i["id"] == "accuracy-gate"), None)
        canary_inv = next((i for i in check["invariants"] if i["id"] == "backdoor-canary"), None)
        gate_line = ("The accuracy gate **passes** (your dashboard shrugs) but the behavioral "
                     "canary **fails** and blocks the ship."
                     if (acc_gate and acc_gate["passed"] and canary_inv and not canary_inv["passed"])
                     else "The accuracy gate itself **fails**: this one is loud enough to catch on accuracy alone.")
        _write(d / "README.md", _card(
            _fm({"tags": ["data-poisoning", "adversarial-machine-learning", "security",
                          "backdoor-attacks", "unrelabel"], "pretty_name": a["title"]}),
            f"# {a['title']}\n\n{DUAL_USE}\n\n"
            f"{HOW[a['slug']]}\n\n"
            f"Planted on the ecommerce review-sentiment base with [unrelabel]({GH}).\n\n"
            f"![dashboard vs reality](assets/effect.png)\n\n"
            f"_{caption}_\n\n"
            f"## What the poison looks like\n{_poison_peek(manifest)}\n\n"
            f"## The damage (measured, not vibes)\n"
            f"- **Poison:** {manifest['operation_count']} rows, {manifest['poison_fraction'] * 100:.1f}% of training\n"
            f"- **Global accuracy:** {state['baseline_accuracy'] * 100:.1f}% then "
            f"{state['poisoned_accuracy'] * 100:.1f}% ({'unmoved' if abs(state['baseline_accuracy'] - state['poisoned_accuracy']) < 0.01 else 'moved'})\n"
            f"- **Stealth:** {metrics['stealth'] * 100:.0f}% (how blind a global-accuracy dashboard is)\n"
            f"- **Efficiency:** {(metrics['asr_per_pct'] or 0) * 100:.0f} points of attack-success per 1% of poison\n"
            f"- **Verdict:** {gate_line}\n\n"
            f"## Files\n"
            "| file | what it is |\n|---|---|\n"
            "| `clean_train.csv` | the training set before anyone touched it |\n"
            "| `poisoned_train.csv` | the same set, now with a hidden agenda |\n"
            "| `test.csv` | shared test split |\n"
            "| `manifest.json` | every operation, reversible and replayable to the row |\n"
            "| `canary.yaml` | the behavioral invariant that catches this attack |\n"
            "| `metrics.json` | the numbers above, in full |\n\n"
            f"## Catch it yourself\n"
            "```bash\n"
            "pip install unrelabel\n"
            "# freeze the fragile behavior, then assert it on any candidate model:\n"
            "unrelabel check your_config.yaml --canary canary.yaml\n"
            "```\n\n"
            f"The trick, the defense, and the rest of the arsenal: {GH}.\n"))
        index.append({"slug": a["slug"], "title": a["title"], "attack": a["type"],
                      "poison_rows": manifest["operation_count"], "poison_fraction": manifest["poison_fraction"],
                      "stealth": metrics["stealth"], "canary_catches": bool(canary_inv and not canary_inv["passed"])})
        print(f"  benchmark/{a['slug']}: {manifest['operation_count']} rows, "
              f"acc {state['baseline_accuracy']:.2f}->{state['poisoned_accuracy']:.2f}, stealth {metrics['stealth']:.2f}")

    _write(root / "index.json", json.dumps(index, indent=2))
    hf_charts.thesis_chart(thesis_rows, root / "assets" / "landscape.png")
    thesis_caption = (
        "Blue is the global test accuracy your dashboard reports; it barely moves, and four "
        "attacks leave it identical at 0.942. Red is what actually happened on the exact slice "
        "each attack aimed at. Each red marker measures a different named population, so read "
        "each row against its own blue dot, not against the other rows. For the four backdoors "
        "red is 1 minus ASR (the share of triggered inputs NOT flipped to the attacker label). "
        "Availability is the honest control: it is the one attack global accuracy actually "
        "catches, so its dots coincide in green.")
    table = "\n".join(
        f"| [{e['title']}](./{e['slug']}) | `{e['attack']}` | {e['poison_rows']} "
        f"({e['poison_fraction'] * 100:.1f}%) | {e['stealth'] * 100:.0f}% | "
        f"{'the canary' if e['canary_catches'] else 'the accuracy gate'} |" for e in index)
    _write(root / "README.md", _card(
        _fm({"tags": ["data-poisoning", "adversarial-machine-learning", "security",
                      "backdoor-attacks", "benchmark", "unrelabel"],
             "pretty_name": "unrelabel poison benchmark", "configs": configs}),
        "# unrelabel poison benchmark\n\n" + DUAL_USE + "\n\n"
        "Six ways to poison a text classifier, each shipped as a matched pair: the clean "
        "training set, the poisoned one, a reversible manifest of exactly what changed, and "
        f"the behavioral canary that catches it. Built with [unrelabel]({GH}).\n\n"
        "The point of the benchmark is the last column. **Accuracy is one number, and it "
        "lies.** Five of these six attacks keep global accuracy perfectly healthy while "
        "quietly turning the model's verdict. Only a behavioral canary notices. The sixth "
        "(availability) is loud on purpose, so you can see the difference.\n\n"
        "![Global accuracy is one number, and it lies](assets/landscape.png)\n\n"
        f"_{thesis_caption}_\n\n"
        "| attack | type | poison | stealth | caught by |\n"
        "|---|---|---|---|---|\n" + table + "\n\n"
        "**Stealth** is how blind a plain accuracy dashboard is to the attack: 100% means it "
        "sees nothing. Pick a config from the dropdown above to browse the poisoned rows, or "
        "open a folder for its full card, manifest, and canary.\n\n"
        "## How to actually use this\n"
        "```bash\n"
        "pip install unrelabel\n"
        "# each folder ships a canary.yaml; assert it against your retrained model:\n"
        "unrelabel check your_config.yaml --canary subpopulation-phone/canary.yaml\n"
        "```\n\n"
        f"Every number here is a measured run, reproducible from the manifests. The tool, the "
        f"attacks, and the defenses: {GH}.\n"))
    print(f"  benchmark -> {root}")


if __name__ == "__main__":
    print(f"Building HF artifacts under {OUT} ...")
    build_demos()
    build_benchmark()
    print(f"Done. Review hf_export/, then run scripts/push_to_hf.py to publish.")
